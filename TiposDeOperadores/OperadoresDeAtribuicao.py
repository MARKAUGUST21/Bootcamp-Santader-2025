saldo = 500 # Atribuição simples
print(saldo)

saldo += 200 # Atribuição com adição 
print(saldo)

saldo -= 100 # Atribuição com subtração
print(saldo)

saldo *= 2 # Atribuição com multiplicação
print(saldo)

saldo /= 4 # Atribuição com divisão
print(saldo)

saldo %= 3 # Atribuição com módulo
print(saldo)

saldo //= 1 # Atribuição com divisão inteira
print(saldo)

saldo **= 4 # Atribuição com exponenciação
print (saldo)
